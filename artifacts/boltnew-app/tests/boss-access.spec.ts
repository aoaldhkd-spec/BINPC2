import { test, expect } from '@playwright/test';
const password=process.env.HUB_E2E_BOSS_PASSWORD;
if(!password)throw Error('Explicit isolated owner credential required');
test('actual React/API/PG: boss-only login, private laboratory persistence, logout and generic-token denial',async({page,request,context},info)=>{
  await context.route('**/*',r=>new URL(r.request().url()).origin===process.env.HUB_E2E_BASE_URL?r.continue():r.abort());
  await page.setViewportSize({width:390,height:844});
  await page.addInitScript(()=>{if(!sessionStorage.getItem('boss-test-seeded')) {sessionStorage.setItem('boss-test-seeded','1');localStorage.setItem('matching_app_user_id','old-synthetic-profile-preserved');localStorage.setItem('admin_token_v1','old-role-token');}});
  await page.goto('/events');
  await expect(page.getByRole('heading',{name:'현재 테스트 중입니다'})).toBeVisible();
  expect(await page.evaluate(()=>localStorage.getItem('matching_app_user_id'))).toBe('old-synthetic-profile-preserved');
  for(const path of ['/api/event-hub/state','/api/db/events','/api/db/storage-image?path=any']) expect((await request.get(path)).status()).toBe(423);
  expect((await request.get('http://127.0.0.1:8123/API/db/op')).status()).toBe(423);
  await page.screenshot({path:info.outputPath('boss-locked-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'운영자 로그인'}).click();
  await page.getByLabel('전화번호',{exact:true}).fill('010-0000-0000');
  await page.getByLabel('비밀번호',{exact:true}).fill(password!);
  await page.getByRole('button',{name:'로그인',exact:true}).click();
  await expect(page.getByText('보스 테스트 중 · 일반 이용은 잠겨 있습니다')).toBeVisible();
  await page.getByRole('link',{name:'관리자',exact:true}).click();
  await page.getByRole('button',{name:'🎉 술번개',exact:true}).click();
  await expect(page.getByText('현재 상태: ON · 테스트 및 점검 중',{exact:true})).toBeVisible();
  await expect(page.getByText('실제 모집: 차단 · 웹·오픈채팅 모두 접수 전',{exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('boss-admin-mobile.png'),fullPage:true});
  const mode=await page.evaluate(async()=>{const r=await fetch('/api/event-hub/laboratory',{headers:{'x-admin-token':localStorage.getItem('admin_token_v1')!}});return r.json();});
  expect(mode.mode).toMatchObject({enabled:true,publicAdmissionOpen:false});
  await page.reload();
  await expect(page.getByText('보스 테스트 중 · 일반 이용은 잠겨 있습니다')).toBeVisible();
  expect(await page.evaluate(()=>localStorage.getItem('admin_pw_v1'))).toBeNull();
  await page.getByRole('button',{name:'테스트 로그아웃',exact:true}).click();
  await expect(page.getByRole('heading',{name:'현재 테스트 중입니다'})).toBeVisible();
  expect((await page.request.get('/api/event-hub/admin')).status()).toBe(423);
  await page.reload();
  await expect(page.getByRole('heading',{name:'현재 테스트 중입니다'})).toBeVisible();
});
